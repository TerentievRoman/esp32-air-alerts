#!/usr/bin/env python3
"""Generate main/font5x8.c from the X11 misc-fixed 5x8 font (public domain).

Usage: python3 tools/font2c.py > main/font5x8.c
Needs Pillow and the xfonts-base package (/usr/share/fonts/X11/misc/5x8.pcf.gz).
"""
import gzip
import sys

from PIL import PcfFontFile

SRC = "/usr/share/fonts/X11/misc/5x8.pcf.gz"
ASCENT = 7          # baseline row in the 8-row cell
WIDTH = 5

# Printable ASCII + the Cyrillic part of cp1251 (А-я, Ґґ Єє Іі Її, Ёё) + ’ — °
CHARS = [chr(c) for c in range(0x20, 0x7F)]
CHARS += [bytes([b]).decode("cp1251") for b in list(range(0xC0, 0x100)) +
          [0xA5, 0xB4, 0xAA, 0xBA, 0xB2, 0xB3, 0xAF, 0xBF, 0xA8, 0xB8, 0x92, 0x97, 0xB0]]

# Hand-drawn replacements (rows top to bottom). X11 5x8 draws capital Ї
# without its dots, which makes it identical to І.
OVERRIDES = {
    "Ї": [".#.#.",
          ".....",
          ".###.",
          "..#..",
          "..#..",
          "..#..",
          ".###.",
          "....."],
}


def rows_to_columns(rows):
    cols = [0] * WIDTH
    for r, line in enumerate(rows):
        for x, px in enumerate(line):
            if px == "#":
                cols[x] |= 1 << r
    return cols


PREAMBLE = '''/* GENERATED by tools/font2c.py from X11 misc-fixed 5x8 (public domain). Do not edit. */
#include "font5x8.h"

#include <stddef.h>

typedef struct {
    uint32_t cp;
    uint8_t col[5];
} font5x8_entry_t;

static const font5x8_entry_t FONT[] = {
'''

POSTAMBLE = '''};

#define FONT_N (sizeof(FONT) / sizeof(FONT[0]))

const uint8_t *font5x8_glyph(uint32_t cp)
{
    size_t lo = 0, hi = FONT_N;
    while (lo < hi) {
        size_t mid = (lo + hi) / 2;
        if (FONT[mid].cp == cp) return FONT[mid].col;
        if (FONT[mid].cp < cp) lo = mid + 1;
        else hi = mid;
    }
    return cp == '?' ? NULL : font5x8_glyph('?');
}

uint32_t utf8_next(const char **s)
{
    const uint8_t *p = (const uint8_t *)*s;
    uint32_t c = p[0];
    if (c == 0) return 0;
    int n;
    if (c < 0x80) { *s += 1; return c; }
    else if ((c & 0xE0) == 0xC0) { n = 1; c &= 0x1F; }
    else if ((c & 0xF0) == 0xE0) { n = 2; c &= 0x0F; }
    else if ((c & 0xF8) == 0xF0) { n = 3; c &= 0x07; }
    else { *s += 1; return 0xFFFD; }
    for (int i = 1; i <= n; i++) {
        if ((p[i] & 0xC0) != 0x80) { *s += 1; return 0xFFFD; }
        c = (c << 6) | (p[i] & 0x3F);
    }
    *s += n + 1;
    return c;
}
'''


def columns(glyph):
    """Glyph -> 5 column bytes (bit 0 = top row of the 8-row cell)."""
    _, bbox, _, im = glyph
    x0, y0 = bbox[0], bbox[1]
    cols = [0] * WIDTH
    w, h = im.size
    for y in range(h):
        row = ASCENT + y0 + y
        if not 0 <= row < 8:
            continue
        for x in range(w):
            col = x0 + x
            if 0 <= col < WIDTH and im.getpixel((x, y)):
                cols[col] |= 1 << row
    return cols


def main():
    font = PcfFontFile.PcfFontFile(gzip.open(SRC, "rb"), charset_encoding="cp1251")
    entries = []
    for ch in CHARS:
        b = ch.encode("cp1251")[0]
        g = font.glyph[b]
        if g is None:
            sys.exit(f"missing glyph for {ch!r}")
        cols = rows_to_columns(OVERRIDES[ch]) if ch in OVERRIDES else columns(g)
        entries.append((ord(ch), cols, ch))
    entries.sort()
    out = [PREAMBLE]
    for cp, cols, ch in entries:
        label = ch if ch not in "\\'" and cp >= 0x21 else f"U+{cp:04X}"
        out.append("    { 0x%04X, { %s } }, /* %s */\n"
                   % (cp, ", ".join(f"0x{c:02X}" for c in cols), label))
    out.append(POSTAMBLE)
    sys.stdout.write("".join(out))


if __name__ == "__main__":
    main()
